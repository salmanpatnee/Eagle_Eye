<article>
    <p>Financial entities shall include in their human resource policy or other relevant policies all of the following ICT security related elements:</p>
<ol type="a">
    <li>The identification and assignment of any specific ICT security responsibilities;</li>
    <li>Requirements for staff of the financial entity and of the ICT third-party service providers using or accessing ICT assets of the financial entity to:
        <ol type="i">
            <li>Be informed about, and adhere to, the financial entity’s ICT security policies, procedures, and protocols;</li>
            <li>Be aware of the reporting channels put in place by the financial entity for the detection of anomalous behaviour, including, where applicable, the reporting channels established in line with Directive (EU) 2019/1937 of the European Parliament and of the Council (11);</li>
            <li>For the staff, to return to the financial entity, upon termination of employment, all ICT assets and tangible information assets in their possession that belong to the financial entity.</li>
        </ol>
    </li>
</ol>
</article>
