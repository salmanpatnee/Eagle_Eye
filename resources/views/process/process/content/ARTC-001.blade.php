<article>

    <p>
        When developing and implementing the ICT security policies, procedures, protocols and tools referred to in Title
        II and the simplified ICT risk management framework referred to in Title III, the size and the overall risk
        profile of the financial entity, and the nature, scale and elements of increased or reduced complexity of its
        services, activities and operations shall be taken into account, including elements relating to:
    </p>

    <ul>
        <li>Encryption and Cryptography</li>
        <li>ICT operations security</li>
        <li>Network security</li>
        <li>ICT project and change management</li>
        <li>The potential impact of the ICT risk on confidentiality, integrity and availability of data, and of the
            disruptions on the continuity and availability of the financial entity’s activities.</li>
    </ul>
</article>
