<article>
<ol>
    <li>
      The financial entities referred to in Article 16(1) of Regulation (EU) 2022/2554 shall design and implement, where appropriate, a procedure governing the acquisition, development, and maintenance of ICT systems following a risk-based approach. That procedure shall:
        <ol type="a">
            <li>Ensure that, before any acquisition or development of ICT systems takes place, the functional and non-functional requirements, including information security requirements, are clearly specified and approved by the business function concerned;</li>
            <li>Ensure the testing and approval of ICT systems prior to their first use and before introducing changes to the production environment;</li>
            <li>Identify measures to mitigate the risk of unintentional alteration or intentional manipulation of the ICT systems during development and implementation in the production environment.</li>
        </ol>
    </li>
</ol>
</article>
