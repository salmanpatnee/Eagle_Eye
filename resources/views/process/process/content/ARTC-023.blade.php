<article>
<ol>
    <li>Financial entities shall set clear roles and responsibilities to effectively detect and respond to ICT-related incidents and anomalous activities.</li>
    <li>The mechanism to promptly detect anomalous activities, including ICT network performance issues and ICT-related incidents, as referred to in Article 10(1) of Regulation (EU) 2022/2554, shall enable financial entities to:
        <ol type="a">
            <li>Collect, monitor, and analyse all of the following:
                <ol type="i">
                    <li>Internal and external factors, including at least the logs collected in accordance with Article 12 of this Regulation, information from business and ICT functions, and any problem reported by users of the financial entity;</li>
                    <li>Potential internal and external cyber threats, considering scenarios commonly used by threat actors and scenarios based on threat intelligence activity;</li>
                    <li>ICT-related incident notification from an ICT third-party service provider of the financial entity detected in the ICT systems and networks of the ICT third-party service provider and that may affect the financial entity;</li>
                </ol>
            </li>
            <li>Identify anomalous activities and behaviour, and implement tools generating alerts for anomalous activities and behaviour, at least for ICT assets and information assets supporting critical or important functions;</li>
            <li>Prioritise the alerts referred to in point (b) to allow for the management of the detected ICT-related incidents within the expected resolution time, as specified by financial entities, both during and outside working hours;</li>
            <li> Record, analyse, and evaluate any relevant information on all anomalous activities and behaviours automatically or manually.</li>
        </ol>
        <p>For the purposes of point (b), the tools referred to in that point shall contain the tools that provide automated alerts based on pre-defined rules to identify anomalies affecting the completeness and integrity of the data sources or log collection.</p>
    </li>
    <li>Financial entities shall protect any recording of the anomalous activities against tampering and unauthorised access at rest, in transit and, where relevant, in use.</li>
    <li>Financial entities shall log all relevant information for each detected anomalous activity enabling:
        <ol type="a">
            <li>The identification of the date and time of occurrence of the anomalous activity;</li>
            <li>The identification of the date and time of detection of the anomalous activity;</li>
            <li>The identification of the type of the anomalous activity.</li>
        </ol>
    </li>
    <li>Financial entities shall consider all of the following criteria to trigger the ICT-related incident detection and response processes referred to in Article 10(2) of Regulation (EU) 2022/2554:
        <ol type="a">
            <li>Indications that malicious activity may have been carried out in an ICT system or network, or that such ICT system or network may have been compromised;</li>
            <li>Data losses detected in relation to the availability, authenticity, integrity, and confidentiality of data;</li>
            <li>Adverse impact detected on financial entity’s transactions and operations;</li>
            <li>ICT systems’ and network unavailability.</li>
        </ol>
    </li>
    <li>For the purposes of paragraph 5, financial entities shall also consider the criticality of the services affected.</li>
</ol>
</article>
