<article>
    <ol>
        <li>
            The financial entities referred to in Article 16(1) of Regulation
            (EU) 2022/2554 shall have in place an internal governance and
            control framework that ensures an effective and prudent management
            of ICT risk to achieve a high level of digital operational
            resilience.
        </li>
        <li>
            The financial entities referred to in paragraph 1 shall, as part of
            their simplified ICT risk management framework, ensure that their
            management body:
            <ol type="a">
                <li>
                    bears the overall responsibility for ensuring that the
                    simplified ICT risk management framework allows for the
                    achievement of the financial entity’s business strategy in
                    accordance with the risk appetite of that financial entity,
                    and ensures that ICT risk is considered in that context;
                </li>
                <li>
                    sets clear roles and responsibilities for all ICT-related
                    tasks;
                </li>
                <li>
                    sets out information security objectives and ICT
                    requirements;
                </li>
                <li>
                    approves, oversees, and periodically reviews:
                    <ol type="i">
                        <li>
                            the classification of information assets of the
                            financial entity as referred to in Article 30(1) of
                            this Regulation, the list of main risks identified,
                            and the business impact analysis and related
                            policies;
                        </li>
                        <li>
                            the business continuity plans of the financial
                            entity, and the response and recovery measures
                            referred to in Article 16(1), point (f), of
                            Regulation (EU) 2022/2554;
                        </li>
                    </ol>
                </li>
                <li>
                    allocates and reviews at least once a year the budget
                    necessary to fulfil the financial entity’s digital
                    operational resilience needs in respect of all types of
                    resources, including relevant ICT security awareness
                    programmes and digital operational resilience training and
                    ICT skills for all staff;
                </li>
                <li>
                    specifies and implements the policies and measures included
                    in Chapters I, II and III of this Title to identify, assess
                    and manage the ICT risk the financial entity is exposed to;
                </li>
                <li>
                    identifies and implements procedures, ICT protocols, and
                    tools that are necessary to protect all information assets
                    and ICT assets;
                </li>
                <li>
                    ensures that the staff of the financial entity is kept up to
                    date with sufficient knowledge and skills to understand and
                    assess ICT risk and its impact on the operations of the
                    financial entity, commensurate to the ICT risk being
                    managed;
                </li>
                <li>
                    establishes reporting arrangements, including the frequency,
                    form, and content of reporting to the management body on the
                    information security and digital operational resilience.
                </li>
            </ol>
        </li>
        <li>
            The financial entities referred to in paragraph 1 may, in accordance
            with Union and national sectoral law, outsource the tasks of
            verifying compliance with ICT risk management requirements to ICT
            intra-group or ICT third-party service providers. In case of such
            outsourcing, financial entities shall remain fully responsible for
            the verification of compliance with the ICT risk management
            requirements.
        </li>
        <li>
            The financial entities referred to in paragraph 1 shall ensure an
            appropriate segregation and the independence of control functions
            and internal audit functions.
        </li>
        <li>
            The financial entities referred to in paragraph 1 shall ensure that
            their simplified ICT risk management framework is subject to an
            internal audit by auditors, in line with the financial entities’
            audit plan. The auditors shall have sufficient knowledge, skills,
            and expertise in ICT risk, and shall be independent. The frequency
            and focus of ICT audits shall be commensurate to the ICT risk of the
            financial entity.
        </li>
        <li>
            Based on the outcome of the audit referred to in paragraph 5, the
            financial entities referred to in paragraph 1 shall ensure the
            timely verification and remediation of critical ICT audit findings.
        </li>
    </ol>
</article>
