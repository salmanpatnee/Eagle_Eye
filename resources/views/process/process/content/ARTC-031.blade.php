<article>
 <ol>
    <li>The financial entities referred to in Article 16(1) of Regulation (EU) 2022/2554 shall include in their simplified ICT risk management framework all of the following:
        <ol type="a">
            <li>A determination of the risk tolerance levels for ICT risk, in accordance with the risk appetite of the financial entity;</li>
            <li>The identification and assessment of the ICT risks to which the financial entity is exposed;</li>
            <li>The specification of mitigation strategies at least for the ICT risks that are not within the risk tolerance levels of the financial entity;</li>
            <li>The monitoring of the effectiveness of the mitigation strategies referred to in point (c);</li>
            <li>The identification and assessment of any ICT and information security risks resulting from any major change in ICT system or ICT services, processes, or procedures, and from ICT security testing results and after any major ICT-related incident.</li>
        </ol>        
    </li>
    <li>
        The financial entities referred to in paragraph 1 shall carry out and document the ICT risk assessment periodically commensurate to the financial entities’ ICT risk profile.
    </li>
    <li>The financial entities referred to in paragraph 1 shall continuously monitor threats and vulnerabilities that are relevant to their critical or important functions, and information assets and ICT assets, and shall regularly review the risk scenarios impacting those critical or important functions.</li>
    <li>The financial entities referred to in paragraph 1 shall set out alert thresholds and criteria to trigger and initiate ICT-related incident response processes.</li>
 </ol>
</article>
