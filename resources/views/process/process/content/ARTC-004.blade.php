<article>
    <ol>
        <li>As part of the ICT security policies, procedures, protocols, and tools referred to in Article 9(2) of Regulation (EU) 2022/2554, financial entities shall develop, document, and implement a policy on management of ICT assets.</li>
        <li>The policy on management of ICT assets referred to in paragraph 1 shall:

            <ol type="a">
                <li>Prescribe the monitoring and management of the lifecycle of ICT assets identified and classified in accordance with Article 8(1) of Regulation (EU) 2022/2554;</li>
                <li>Prescribe that the financial entity keeps records of all of the following:
                    <ol type="i">
                        <li>The unique identifier of each ICT asset;</li>
                        <li>Information on the location, either physical or logical, of all ICT assets;</li>
                        <li>The classification of all ICT assets, as referred to in Article 8(1) of Regulation (EU) 2022/2254;</li>
                        <li>The identity of ICT asset owners;</li>
                        <li>The business functions or services supported by the ICT asset;</li>
                        <li>The ICT business continuity requirements, including recovery time objectives and recovery point objectives;</li>
                        <li>Whether the ICT asset can be or is exposed to external networks, including the internet;</li>
                        <li>The links and interdependencies among ICT assets and the business functions using each ICT asset;</li>
                        <li>Where applicable, for all ICT assets, the end dates of the ICT third-party service provider’s regular, extended, and custom support services after which those ICT assets are no longer supported by their supplier or by an ICT third-party service provider;</li>
                    </ol>
                </li>
                <li>For financial entities other than microenterprises, prescribe that those financial entities keep records of the information necessary to perform a specific ICT risk assessment on all legacy ICT systems referred to in Article 8(7) of Regulation (EU) 2022/2554.</li>
            </ol>
        </li>
    </ol>

</article>
