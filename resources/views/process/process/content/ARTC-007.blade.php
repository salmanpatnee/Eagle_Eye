<article>
    <ol>
        <li>Financial entities shall include in the cryptographic key management policy referred to in Article 6(2),
            point (d), requirements for managing cryptographic keys through their whole lifecycle, including generating,
            renewing, storing, backing up, archiving, retrieving, transmitting, retiring, revoking, and destroying those
            cryptographic keys.</li>
        <li>Financial entities shall identify and implement controls to protect cryptographic keys through their whole
            lifecycle against loss, unauthorised access, disclosure, and modification. Financial entities shall design
            those controls on the basis of the results of the approved data classification and the ICT risk assessment.
        </li>

        <li>Financial entities shall develop and implement methods to replace the cryptographic keys in the case of
            loss, or where those keys are compromised or damaged.</li>
        <li>Financial entities shall create and maintain a register for all certificates and certificate-storing devices
            for at least ICT assets supporting critical or important functions. Financial entities shall keep that
            register up to date.</li>
        <li>Financial entities shall ensure the prompt renewal of certificates in advance of their expiration.</li>
    </ol>
</article>
