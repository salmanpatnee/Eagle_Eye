<article>
  <ol>
    <li>As part of the ICT security policies, procedures, protocols, and tools referred to in Article 9(2) of Regulation (EU) 2022/2554, financial entities shall develop, document, and implement policies and procedures to manage the ICT operations. Those policies and procedures shall specify how financial entities operate, monitor, control, and restore their ICT assets, including the documentation of ICT operations.</li>
    <li>The policies and procedures for ICT operations referred to in paragraph 1 shall contain all of the following:
        <ol type="a">
            <li>An ICT assets description, including all of the following:
                <ol type="i">
                    <li>Requirements regarding secure installation, maintenance, configuration, and deinstallation of an ICT system;</li>
                    <li>Requirements regarding the management of information assets used by ICT assets, including their processing and handling, both automated and manual</li>
                    <li>Requirements regarding the identification and control of legacy ICT systems</li>
                </ol>
                <li>Controls and monitoring of ICT systems, including all of the following
                    <ol type="i">
                        <li>Backup and restore requirements of ICT systems;</li>
                        <li>Scheduling requirements, taking into consideration interdependencies among the ICT systems;</li>
                        <li>Protocols for audit-trail and system log information;</li>
                        <li>Requirements to ensure that the performance of internal audit and other testing minimises disruptions to business operations</li>
                        <li>Requirements on the separation of ICT production environments from the development, testing, and other non-production environments;</li>
                        <li> Requirements to conduct the development and testing in environments which are separated from the production environment;</li>
                        <li>Requirements to conduct the development and testing in production environments;</li>
                    </ol>
                    <li>Error handling concerning ICT systems, including all of the following
                        <ol type="i">
                            <li>Procedures and protocols for handling errors</li>
                            <li>Support and escalation contacts, including external support contacts in case of unexpected operational or technical issues</li>
                            <li>ICT system restart, rollback, and recovery procedures for use in the event of ICT system disruption.</li>
                        </ol>
                    </li>
                </li>
            </li>
        </ol>
    </li>
  </ol>
  <p>For the purposes of point (b)(v), the separation shall consider all of the components of the environment, including accounts, data or connections, as required by Article 13, first subparagraph, point (a).</p>
  <p>For the purposes of point (b) (vii), the policies and procedures referred to in paragraph 1 shall provide that the instances in which testing is performed in a production environment are clearly identified, reasoned, are for limited periods of time, and are approved by the relevant function in accordance with Article 16(6). Financial entities shall ensure the availability, confidentiality, integrity, and authenticity of ICT systems and production data during development and test activities in the production environment.</p>
</article>
