<article>
    <ol>
        <li>Financial entities shall, as part of the safeguards against intrusions and data misuse, develop, document, and implement logging procedures, protocols and tools.</li>
        <li>The logging procedures, protocols, and tools referred to in paragraph 1 shall contain all of the following:
            <ol type="a">
                <li>The identification of the events to be logged, the retention period of the logs, and the measures to secure and handle the log data, considering the purpose for which the logs are created;</li>
                <li>The alignment of the level of detail of the logs with their purpose and usage to enable the effective detection of anomalous activities as referred to in Article 24</li>
                <li>The requirement to log events related to all of the following
                    <ol type="i">
                        <li>Logical and physical access control, as referred to in Article 21, and identity management;</li>
                        <li>Capacity management;</li>
                        <li>Change management;</li>
                        <li>ICT operations, including ICT system activities;</li>
                        <li>Network traffic activities, including ICT network performance;</li>
                    </ol>
                </li>
                <li>Measures to protect logging systems and log information against tampering, deletion, and unauthorised access at rest, in transit, and, where relevant, in use;</li>
                <li>Measures to detect a failure of logging systems;</li>
                <li>Without prejudice to any applicable regulatory requirements under Union or national law, the synchronisation of the clocks of each of the financial entity’s ICT systems upon a documented reliable reference time source.</li>
            </ol>
        </li>
        <p>For the purposes of point (a), financial entities shall establish the retention period, taking into account the business and information security objectives, the reason for recording the event in the logs, and the results of the ICT risk assessment.</p>
    </ol>
</article>
