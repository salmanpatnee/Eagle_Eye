<article>
 <ol>
    <li>As part of the simplified ICT risk management framework referred to in Article 16(1), point (a), of Regulation (EU) 2022/2554, the financial entities referred to in paragraph 1 of that Article shall identify, classify, and document all critical or important functions, the information assets and ICT assets supporting them and their interdependencies. Financial entities shall review that identification and classification as needed.
    </li>
    <li>The financial entities referred to in paragraph 1 shall identify all critical or important functions supported by ICT third-party service providers.</li>
 </ol>
</article>
