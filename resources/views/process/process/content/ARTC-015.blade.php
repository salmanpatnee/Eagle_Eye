<article>
  <ol>
    <li>As part of the safeguards to preserve the availability, authenticity, integrity, and confidentiality of data, financial entities shall develop, document, and implement an ICT project management policy.</li>
    <li>The ICT project management policy referred to in paragraph 1 shall specify the elements that ensure the effective management of the ICT projects related to the acquisition, maintenance and, where applicable, development of the financial entity’s ICT systems.</li>
    <li>The ICT project management policy referred to in paragraph 1 shall contain all of the following
        <ol type="a">
            <li>ICT project objectives</li>
            <li>ICT project governance, including roles and responsibilities</li>
            <li>ICT project planning, timeframe, and steps</li>
            <li>ICT project risk assessment</li>
            <li>Relevant milestones</li>
            <li>Change management requirements</li>
            <li>The testing of all requirements, including security requirements, and the respective approval process when deploying an ICT system in the production environment</li>
            <li>The testing of all requirements, including security requirements, and the respective approval process when deploying an ICT system in the production environment</li>
        </ol>
    </li>
    <li>The ICT project management policy referred to in paragraph 1 shall ensure the secure ICT project implementation through the provision of the necessary information and expertise from the business area or functions impacted by the ICT project.</li>
    <li>In accordance with the ICT project risk assessment referred to in paragraph 3, point (d), the ICT project management policy referred to in paragraph 1 shall provide that the establishment and progress of ICT projects impacting critical or important functions of the financial entity and their associated risks are reported to the management body as follows:
        <ol type="a">
            <li>Individually or in aggregation, depending on the importance and size of the ICT projects</li>
            <li>Periodically and, where necessary, on an event-driven basis</li>
        </ol>
    </li>
  </ol>
</article>
