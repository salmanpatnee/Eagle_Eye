<article>
<ol>
    <li>
        As part of the ICT security policies, procedures, protocols, and tools referred to in Article 9(2) of Regulation (EU) 2022/2554, financial entities shall develop, document, and implement capacity and performance management procedures for the following:
        <ol type="a">
            <li>The identification of capacity requirements of their ICT systems;</li>
            <li>The application of resource optimisation</li>
            <li>The monitoring procedures for maintaining and improving
                <ol type="i">
                    <li>The availability of data and ICT systems</li>
                    <li>The efficiency of ICT systems</li>
                    <li>The prevention of ICT capacity shortages.</li>
                </ol>
            </li>

        </ol>
    </li>
    <li>The capacity and performance management procedures referred to in paragraph 1 shall ensure that financial entities take measures that are appropriate to cater for the specificities of ICT systems with long or complex procurement or approval processes or ICT systems that are resource-intensive.</li>
</ol>
</article>
