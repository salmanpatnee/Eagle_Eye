<article>
    <p>Financial entities shall develop, document, and implement ICT risk management policies and procedures that shall contain all of the following:</p>
    <ol type="a">
        <li>An indication of the approval of the risk tolerance level for ICT risk established in accordance with Article 6(8), point (b), of Regulation (EU) 2022/2554;
        </li>
        <li>A procedure and a methodology to conduct the ICT risk assessment, identifying:
            <ol type="i">
                <li>Vulnerabilities and threats that affect or may affect the supported business functions, the ICT systems and ICT assets supporting those functions;</li>
                <li>The quantitative or qualitative indicators to measure the impact and likelihood of the vulnerabilities and threats referred to in point (i);</li>
            </ol>
        </li>
        <li>
            The procedure to identify, implement, and document ICT risk treatment measures for the ICT risks identified and assessed, including the determination of ICT risk treatment measures necessary to bring ICT risk within the risk tolerance level referred to in point (a);
        </li>
        <li>For the residual ICT risks that are still present following the implementation of the ICT risk treatment measures referred to in point (c):

            <ol type="i">
                <li>Provisions on the identification of those residual ICT risks;</li>
                <li>The assignment of roles and responsibilities regarding:
                    <ol type="1">
                        <li>The acceptance of the residual ICT risks that exceed the financial entity’s risk tolerance level referred to in point (a);</li>
                        <li>For the review process referred to in point (iv) of this point (d);</li>
                    </ol>
                </li>
                <li>The development of an inventory of the accepted residual ICT risks, including a justification for their acceptance;</li>
                <li>Provisions on the review of the accepted residual ICT risks at least once a year, including:
                    <ol type="1">
                        <li>The identification of any changes to the residual ICT risks;</li>
                        <li>The assessment of available mitigation measures</li>
                        <li>The assessment of whether the reasons justifying the acceptance of residual ICT risks are still valid and applicable at the date of the review</li>
                    </ol>
                </li>
                <li>Provisions on the monitoring of:
                    <ol type="i">
                        <li>Any changes to the ICT risk and cyber threat landscape;</li>
                        <li>Internal and external vulnerabilities and threats:</li>
                        <li>ICT risk of the financial entity that enables promp detection of changes that could affect its ICT risk profile;</li>
                    </ol>
                    <li>Provisions on a process to ensure that any changes to the business strategy and the digital operational resilience strategy of the financial entity are taken into account.</li>
                </li>
            </ol>
            <p>
                For the purposes of the first paragraph, point (c), the procedure referred to in that point shall ensure:
            </p>
            <ol type="a">
                <li>The monitoring of the effectiveness of the ICT risk treatment measures implemented;</li>
                <li>The assessment of whether the established risk tolerance levels of the financial entity have been attained;</li>
                <li>The assessment of whether the financial entity has taken actions to correct or improve those measures where necessary.</li>
            </ol>
        </li>
    </ol>
 
</article>
