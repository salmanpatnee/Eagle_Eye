<article>
    <ol>
        <li>
            As part of the ICT security policies, procedures, protocols, and
            tools referred to in Article 9(2) of Regulation (EU) 2022/2554,
            financial entities shall develop, document, and implement
            vulnerability management procedures.
        </li>
        <li>The vulnerability management procedures referred to in paragraph 1 shall:
            <ol type="a">
                <li>Identify and update relevant and trustworthy information resources to build and maintain awareness about vulnerabilities;</li>
                <li>Ensure the performance of automated vulnerability scanning and assessments on ICT assets, whereby the frequency and scope of those activities shall be commensurate to the classification established in accordance with Article 8(1) of Regulation (EU) 2022/2554 and the overall risk profile of the ICT asset</li>
                <li>Verify whether
                    <ol type="i">
                        <li>ICT third-party service providers handle vulnerabilities related to the ICT services provided to the financial entity</li>
                        <li>Whether those service providers report to the financial entity at least the critical vulnerabilities and statistics and trends in a timely manner</li>
                    </ol>
                </li>
                <li>Track the usage of:
                    <ol type="i">
                        <li>Third-party libraries, including open-source libraries, used by ICT services supporting critical or important functions;</li>
                        <li>ICT services developed by the financial entity itself or specifically customised or developed for the financial entity by an ICT third-party service provider</li>
                    </ol>
                </li>
                <li>Establish procedures for the responsible disclosure of vulnerabilities to clients, counterparties, and to the public</li>
                <li>Prioritise the deployment of patches and other mitigation measures to address the vulnerabilities identified</li>
                <li>Monitor and verify the remediation of vulnerabilities</li>
                <li>Require the recording of any detected vulnerabilities affecting ICT systems and the monitoring of their resolution</li>
                <li></li>
            </ol>
            <p>For the purposes of point (b), financial entities shall perform the automated vulnerability scanning and assessments on ICT assets for the ICT assets supporting critical or important functions on at least a weekly basis.</p>
            <p>For the purposes of point (c), financial entities shall request that ICT third-party service providers investigate the relevant vulnerabilities, determine the root causes, and implement appropriate mitigating action.</p>
            <p>For the purposes of point (d), financial entities shall, where appropriate in collaboration with the ICT third-party service provider, monitor the version and possible updates of the third-party libraries. In case of ready to use (off-the-shelf) ICT assets or components of ICT assets acquired and used in the operation of ICT services not supporting critical or important functions, financial entities shall track the usage to the extent possible of third-party libraries, including open-source libraries.</p>
            <p>For the purposes of point (f), financial entities shall consider the criticality of the vulnerability, the classification established in accordance with Article 8(1) of Regulation (EU) 2022/2554, and the risk profile of the ICT assets affected by the identified vulnerabilities.</p>
        </li>
        <li>As part of the ICT security policies, procedures, protocols, and tools referred to in Article 9(2) of Regulation (EU) 2022/2554, financial entities shall develop, document and implement patch management procedures.</li>
        <li>The patch management procedures referred to in paragraph 3 shall:
            <ol type="a">
                <li>To the extent possible identify and evaluate available software and hardware patches and updates using automated tools;</li>
                <li>Identify emergency procedures for the patching and updating of ICT assets;</li>
                <li>Test and deploy the software and hardware patches and the updates referred to in Article 8(2), points (b)(v), (vi) and (vii)</li>
                <li>Set deadlines for the installation of software and hardware patches and updates and escalation procedures in case those deadlines cannot be met.</li>
            </ol>
        </li>
    </ol>
</article>
