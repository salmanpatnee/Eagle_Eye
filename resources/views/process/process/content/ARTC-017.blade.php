<article>
<ol>
    <li>As part of the safeguards to preserve the availability, authenticity, integrity, and confidentiality of data, financial entities shall include in the ICT change management procedures referred to in Article 9(4), point (e), of Regulation (EU) 2022/2554, in respect of all changes to software, hardware, firmware components, systems, or security parameters, all of the following elements.
        <ol type="a">
            <li>A verification of whether the ICT security requirements have been met</li>
            <li>Mechanisms to ensure the independence of the functions that approve changes and the functions responsible for requesting and implementing those changes</li>
            <li>A clear description of the roles and responsibilities to ensure that:
                <ol type="i">
                    <li>Changes are specified and planned</li>
                    <li>An adequate transition is designed</li>
                    <li>The changes are tested and finalised in a controlled manner</li>
                    <li>There is an effective quality assurance</li>
                </ol>
            </li>
            <li>The documentation and communication of change details, including
                <ol type="i">
                    <li>The purpose and scope of the change</li>
                    <li>The timeline for the implementation of the change</li>
                    <li>The expected outcomes</li>
                </ol>
            </li>
            <li>The identification of fall-back procedures and responsibilities, including procedures and responsibilities for aborting changes or recovering from changes not successfully implemented;</li>
            <li>Procedures, protocols, and tools to manage emergency changes that provide adequate safeguards;</li>
            <li>Procedures to document, re-evaluate, assess, and approve emergency changes after their implementation, including workarounds and patches;</li>
            <li>The identification of the potential impact of a change on existing ICT security measures and an assessment of whether such change requires the adoption of additional ICT security measures.</li>
        </ol>
    </li>
    <li>After having made significant changes to their ICT systems, central counterparties and central securities depositories shall submit their ICT systems to stringent testing by simulating stressed conditions.
        <p>Central counterparties shall involve, as appropriate, in the design and conduct of the testing referred to in the first subparagraph:</p>
        <ol type="a">
            <li>Clearing members and clients</li>
            <li>Interoperable central counterparties</li>
            <li>Other interested parties</li>
        </ol>
        <p>Central securities depositories shall, as appropriate, involve in the design and conduct of the testing referred to in the first subparagraph:</p>
        <ol type="a">
            <li>Users</li>
            <li>Critical utilities and critical service providers</li>
            <li>Other central securities depositories</li>
            <li>Other market infrastructures</li>
            <li>Any other institutions with which central securities depositories have identified interdependencies in their ICT business continuity policy.</li>
        </ol>
    </li>
</ol>
</article>
