<article>
    <ol>
        <li>Financial entities shall ensure that their ICT security policies, information security, and related
            procedures, protocols, and tools as referred to in Article 9(2) of Regulation (EU) 2022/2554 are embedded in
            their ICT risk management framework. Financial entities shall establish the ICT security policies,
            procedures, protocols, and tools laid down in this Chapter that:
            <ol type="a">
                <li>Ensure the security of networks</li>
                <li>Contain safeguards against intrusions and data misuse</li>
                <li>Preserve the availability, authenticity, integrity, and confidentiality of data, including via the
                    use of cryptographic techniques</li>
                <li>Guarantee an accurate and prompt data transmission without major disruptions and undue delays.</li>
            </ol>
        </li>
        <li>
            Financial entities shall ensure that the ICT security policies referred to in paragraph 1:
            <ol type="a">
                <li>Are aligned to the financial entity’s information security objectives included in the digital
                    operational resilience strategy referred to in Article 6(8) of Regulation (EU) 2022/2554;</li>
                <li>Indicate the date of the formal approval of the ICT security policies by the management body;</li>
                <li>Contain indicators and measures to:
                    <ol type="i">
                        <li>Monitor the implementation of the ICT security policies, procedures, protocols, and tools;
                        </li>
                        <li>Record exceptions from that implementation;</li>
                        <li>Ensure that the digital operational resilience of the financial entity is ensured in case of
                            exceptions as referred to in point (ii);</li>
                    </ol>
                <li>Specify the responsibilities of staff at all levels to ensure the financial entity’s ICT security;
                </li>

                <li>Specify the consequences of non-compliance by staff of the financial entity with the ICT security
                    policies, where provisions to that effect are not laid down in other policies of the financial
                    entity;
                </li>
                <li>List the documentation to be maintained;</li>
                <li>Specify the segregation of duties arrangements in the context of the three lines of defence model or other internal risk management and control model, as applicable, to avoid conflicts of interest;</li>
                <li>Consider leading practices and, where applicable, standards as defined in Article 2, point (1), of Regulation (EU) No 1025/2012;</li>
                <li>Identify the roles and responsibilities for the development, implementation and maintenance of ICT security policies, procedures, protocols, and tools;</li>
                <li>Are reviewed in accordance with Article 6(5) of Regulation (EU) 2022/2554;</li>
                <li>Take into account material changes concerning the financial entity, including material changes to the activities or processes of the financial entity, to the cyber threat landscape, or to applicable legal obligations.</li>
        </li>
        </li>
    </ol>
    </li>
    </ol>
</article>
